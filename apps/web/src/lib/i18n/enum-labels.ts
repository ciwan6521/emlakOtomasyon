export const ENUM_LABELS: Record<Locale, GroupLabels> = {
  [Locale.EN]: en,
  [Locale.TR]: tr,
  [Locale.RU]: ru,
  [Locale.ME]: me,
};

/** Falls back to the English label, then to a humanised version of the key. */
export function enumLabel(
  locale: Locale,
  group: EnumGroup,
  value: string | null | undefined,
): string {
  if (!value) return "";
  return (
    ENUM_LABELS[locale]?.[group]?.[value] ??
    en[group][value] ??
    value.replace(/_/g, " ").toLowerCase().replace(/^\w/, (c) => c.toUpperCase())
  );
}
